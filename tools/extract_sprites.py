"""Extracts the small Office XP balloon sprites (bullet, 'see more' arrow, warning icon)
from the reference screenshots and emits them as a C# source file.
Pixels equal to the balloon background (#FFFFCC) become transparent."""
import sys
from PIL import Image

SPRITES = [
    ("Bullet", "Screenshots/Screenshot 2026-10-15 204134.png", (30, 63, 48, 79)),
    ("SeeMoreArrow", "Screenshots/Screenshot 2026-10-15 204134.png", (29, 185, 49, 197)),
    ("Warning", "Screenshots/Screenshot 2026-10-15 204312.png", (20, 13, 56, 47)),
]
BG = (255, 255, 204)

def crop(path, box):
    im = Image.open(path).convert("RGB").crop(box)
    w, h = im.size
    px = [im.getpixel((x, y)) for y in range(h) for x in range(w)]
    # trim fully transparent borders
    rows = [y for y in range(h) if any(px[y * w + x] != BG for x in range(w))]
    cols = [x for x in range(w) if any(px[y * w + x] != BG for y in range(h))]
    x0, x1, y0, y1 = min(cols), max(cols) + 1, min(rows), max(rows) + 1
    out = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            p = px[y * w + x]
            out.append(0 if p == BG else 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2])
    return x1 - x0, y1 - y0, out, (box[0] + x0, box[1] + y0)

def main(out_path):
    lines = ["// <auto-generated> by tools/extract_sprites.py from the reference screenshots </auto-generated>",
             "namespace OfficeAssistant.Core.Rendering;", "",
             "/// <summary>The Office XP balloon bullet, \"See more\" arrow and warning icon.</summary>",
             "public static partial class BalloonSprites", "{"]
    for name, path, box in SPRITES:
        w, h, data, origin = crop(path, box)
        lines.append(f"    // {w}x{h}, taken from {path.split('/')[-1]} at {origin}")
        lines.append(f"    public static readonly Sprite {name} = new({w}, {h}, new uint[]")
        lines.append("    {")
        for y in range(h):
            lines.append("        " + ", ".join(f"0x{v:08X}" for v in data[y * w:(y + 1) * w]) + ",")
        lines.append("    });")
        lines.append("")
    lines.append("}")
    open(out_path, "w", newline="\n").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1])
